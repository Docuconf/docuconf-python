@needs_cue
def test_export_matches_data_after_cue_export(tmp_path: Path) -> None:
    """The CUE text and contract_data() agree (cue export to JSON)."""
    r = vet(docuconf.to_contract(GatewaySettings), tmp_path)
    assert r.returncode == 0
    assert CUE is not None
    exported = subprocess.run(
        [CUE, "export", "./svc", "--out", "json"], cwd=tmp_path, capture_output=True, text=True, check=True
    )
    got = json.loads(exported.stdout)
    want = docuconf.contract_data(GatewaySettings)
    assert got["vars"]["PORT"] == {**want["vars"]["PORT"], "required": False, "secret": False, "name": "PORT"}
    assert got["files"]["routes"]["schema"] == want["files"]["routes"]["schema"]


