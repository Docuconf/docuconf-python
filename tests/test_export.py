def vet(contract: str, tmp_path: Path) -> subprocess.CompletedProcess[str]:
    """Copy the meta-schema module to a temp dir and vet ``contract`` as package ./svc."""
    shutil.copytree(SPEC_CUE / "cue.mod", tmp_path / "cue.mod")
    shutil.copytree(SPEC_CUE / "contract", tmp_path / "contract")
    (tmp_path / "svc").mkdir()
    (tmp_path / "svc/contract.cue").write_text(contract)
    assert CUE is not None
    return subprocess.run([CUE, "vet", "-c", "./svc"], cwd=tmp_path, capture_output=True, text=True)


