def problems(cls: type[BaseSettings]) -> str:
    docuconf.declaration.__globals__["_cache"].pop(cls, None)  # type: ignore[attr-defined]
    with pytest.raises(DeclarationError) as info:
        docuconf.to_contract(cls, name="svc")
    return str(info.value)


def test_declaration_errors() -> None:
    class S(BaseSettings):
        # pydantic's default Rust engine already rejects lookaround; python-re does not.
        model_config = SettingsConfigDict(env_prefix="APP_", regex_engine="python-re")
        short: str = Field(description="tiny")
        nodesc: int = 3
        look: str = Field("abc", description="Lookahead pattern", pattern=r"^(?=a)\w+$")
        backref: str = Field("aa", description="Backreference pattern", pattern=r"(a)\1")
        bad_default: int = Field(0, description="Default out of range", ge=1)
        secret_default: SecretStr = Field(SecretStr("x"), description="Secret with a default")
        csv_only: Annotated[list[str], Csv()] = Field(default_factory=list, description="Csv without NoDecode")
        ints: Literal[1, 2] = Field(1, description="Literal of ints")
        ks: Annotated[Keystore, KeystoreFile(path="/etc/app/ks/ks.p12", password_var="APP_SHORT")] = Field(
            description="Keystore with a non-secret password var"
        )
        lic: Annotated[str, TextFile(path="relative/license.key")] = Field(description="Licence file")

    msg = problems(S)
    for needle in (
        "APP_SHORT (short): needs a description",
        "APP_NODESC (nodesc): needs a description",
        "lookahead",
        "backreference",
        "APP_BAD_DEFAULT (bad_default): default 0 does not satisfy",
        "a secret must not have a default",
        "docuconf.Csv needs NoDecode",
        "enum values must be strings",
        "password_var APP_SHORT must name a declared secret variable",
        "path 'relative/license.key' must be absolute",
    ):
        assert needle in msg, needle


def test_name_rules() -> None:
    class S(BaseSettings):
        model_config = SettingsConfigDict(case_sensitive=True)
        port: int = Field(8080, description="HTTP listen port")

    assert "env name must match" in problems(S)

    class Ok(BaseSettings):
        port: int = Field(8080, description="HTTP listen port")

    with pytest.raises(DeclarationError):
        docuconf.to_contract(Ok, name="Not_A_Label")


def test_path_env_must_not_be_a_var() -> None:
    class S(BaseSettings):
        lic: Annotated[str, TextFile(path="/etc/app/lic/license.key", path_env="LICENSE_FILE")] = Field(
            description="Licence file"
        )
        license_file: str = Field("x", description="Clashes with pathEnv")

    assert "pathEnv LICENSE_FILE must not also be a declared variable" in problems(S)


def test_warnings() -> None:
    class S(BaseSettings):
        enable_checkout: bool = Field(False, description="Deploy-time kill switch")
        hosts: Annotated[list[str], NoDecode] = Field(default_factory=list, description="Hosts, split by a validator")
        ratio: float = Field(0.5, description="Exclusive bound", gt=0)

    warnings = docuconf.declaration(S).warnings
    assert any("ENABLE_CHECKOUT: looks like a feature flag" in w for w in warnings)
    assert any("NoDecode without docuconf.Csv" in w for w in warnings)
    assert any("gt is exported as an inclusive min" in w for w in warnings)


def test_deprecated_and_examples() -> None:
    class S(BaseSettings):
        db_url: str = Field(
            "postgres://x",
            description="Old database URL",
            deprecated="use DATABASE_URL",
            json_schema_extra=None,
        )
        tags: list[str] = Field(default_factory=lambda: ["a"], description="Tags for metrics", examples=[["a", "b"]])

    data = docuconf.contract_data(S, name="svc")
    assert data["vars"]["DB_URL"]["deprecated"] == {"message": "use DATABASE_URL"}
    assert data["vars"]["TAGS"]["default"] == ["a"]


def test_durations() -> None:
    assert to_go(timedelta(minutes=90)) == "1h30m"
    assert to_go("90m") == "1h30m"
    assert to_go(timedelta(milliseconds=1500)) == "1s500ms"
    assert to_go(timedelta(0)) == "0s"
    assert parse_go_duration("1.5h") == 5400 * 10**9
    assert format_go_duration(parse_go_duration("2h45m30s")) == "2h45m30s"
    with pytest.raises(ValueError):
        parse_go_duration("5 minutes")


